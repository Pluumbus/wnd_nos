-- Таблица для стеклопакетов
-- СПО - однокамерный, СПД - двухкамерный
-- И - энергосберегающий, AR - аргон

CREATE TABLE IF NOT EXISTS public.glass_packages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  code text NOT NULL UNIQUE,
  name text NOT NULL,
  thickness integer NOT NULL, -- Толщина в мм
  price numeric NOT NULL DEFAULT 0, -- Цена за кв.м.
  description text,
  is_energy_saving boolean DEFAULT false,
  has_argon boolean DEFAULT false,
  chamber_type text DEFAULT 'double' -- 'single' или 'double'
);

-- Индекс для быстрого поиска по толщине
CREATE INDEX IF NOT EXISTS idx_glass_packages_thickness ON public.glass_packages(thickness);

-- Индекс для поиска по коду
CREATE INDEX IF NOT EXISTS idx_glass_packages_code ON public.glass_packages(code);

