-- Создание таблицы секций окна
create table public.wnd_sections (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  wnd_construction_id bigint not null,
  section_id text not null,           -- "section_0", "section_1", etc.
  width_mm integer null,              -- Ширина секции в мм
  height_mm integer null,             -- Высота секции в мм
  opening_side text null,             -- "left", "right", "top", "bottom", "fixed", "single"
  opening_type text null,             -- "tilt_turn", "turn", "tilt", "fixed"
  has_handle boolean default false,
  constraint wnd_sections_pkey primary key (id),
  constraint wnd_sections_wnd_construction_fkey foreign key (wnd_construction_id) 
    references wnd_constructions (id) on delete cascade on update cascade
) tablespace pg_default;

-- Индекс для быстрого поиска секций по конструкции
create index idx_wnd_sections_construction on public.wnd_sections (wnd_construction_id);
