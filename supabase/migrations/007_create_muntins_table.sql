-- Таблица для раскладок (шпросов)
-- Цены за погонный метр

CREATE TABLE IF NOT EXISTS public.muntins (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  width integer NOT NULL UNIQUE, -- Ширина раскладки в мм
  price_white numeric NOT NULL DEFAULT 0,
  price_gold numeric NOT NULL DEFAULT 0,
  price_brown numeric NOT NULL DEFAULT 0,
  price_colored numeric NOT NULL DEFAULT 0
);

-- Вставляем данные раскладок
INSERT INTO public.muntins (width, price_white, price_gold, price_brown, price_colored) VALUES
  (8, 4400, 2800, 4400, 9800),
  (18, 2400, 6400, 4400, 9800),
  (26, 4400, 4400, 4400, 9800)
ON CONFLICT (width) DO UPDATE SET
  price_white = EXCLUDED.price_white,
  price_gold = EXCLUDED.price_gold,
  price_brown = EXCLUDED.price_brown,
  price_colored = EXCLUDED.price_colored;

-- Комментарий
COMMENT ON TABLE public.muntins IS 'Справочник раскладок (шпросов) с ценами по цветам за п.м.';
