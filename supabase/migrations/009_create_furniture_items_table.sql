-- Таблица для систем фурнитуры
CREATE TABLE IF NOT EXISTS public.furniture_systems (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  code text NOT NULL UNIQUE,
  name text NOT NULL
);

-- Вставляем системы фурнитуры
INSERT INTO public.furniture_systems (code, name) VALUES
  ('FUTURUS', 'FUTURUS'),
  ('ELEMENTS', 'ELEMENTS'),
  ('UPT', 'UPT'),
  ('DOOR', 'Дверная фурнитура')
ON CONFLICT (code) DO UPDATE SET
  name = EXCLUDED.name;

-- Таблица для элементов фурнитуры
CREATE TABLE IF NOT EXISTS public.furniture_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  system_id bigint REFERENCES public.furniture_systems(id),
  code text NOT NULL UNIQUE,
  name text NOT NULL,
  price numeric NOT NULL DEFAULT 0,
  price_alt numeric, -- Альтернативная цена (коричневый и т.д.)
  min_size integer, -- Минимальный размер в мм
  max_size integer, -- Максимальный размер в мм
  category text, -- Категория: drive, scissors, hinge, corner, lock, plate, etc
  description text
);

-- Индексы
CREATE INDEX IF NOT EXISTS idx_furniture_items_system ON public.furniture_items(system_id);
CREATE INDEX IF NOT EXISTS idx_furniture_items_code ON public.furniture_items(code);
CREATE INDEX IF NOT EXISTS idx_furniture_items_category ON public.furniture_items(category);

