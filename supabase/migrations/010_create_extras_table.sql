-- Таблица для цен на москитные сетки
CREATE TABLE IF NOT EXISTS public.mosquito_net_prices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  component text NOT NULL UNIQUE, -- 'frame_white', 'frame_brown', 'mesh'
  name text NOT NULL,
  price numeric NOT NULL DEFAULT 0, -- за п.м. или кв.м.
  unit text DEFAULT 'per_meter' -- 'per_meter' или 'per_sqm'
);

-- Вставляем данные москитных сеток
INSERT INTO public.mosquito_net_prices (component, name, price, unit) VALUES
  ('frame_white', 'Профиль москитки белый', 700, 'per_meter'),
  ('frame_brown', 'Профиль москитки коричневый', 900, 'per_meter'),
  ('mesh', 'Сетка москитная', 800, 'per_sqm')
ON CONFLICT (component) DO UPDATE SET
  name = EXCLUDED.name,
  price = EXCLUDED.price,
  unit = EXCLUDED.unit;

-- Таблица для армирования
CREATE TABLE IF NOT EXISTS public.reinforcement_prices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  profile_type text NOT NULL, -- 'LZ' или 'T'
  thickness text NOT NULL, -- '1.2', '1.5', '2.0'
  price numeric NOT NULL DEFAULT 0, -- за п.м.
  UNIQUE(profile_type, thickness)
);

-- Вставляем данные армирования
INSERT INTO public.reinforcement_prices (profile_type, thickness, price) VALUES
  ('LZ', '1.2', 800),
  ('LZ', '1.5', 1000),
  ('LZ', '2.0', 1200),
  ('T', '1.2', 1000),
  ('T', '1.5', 1200),
