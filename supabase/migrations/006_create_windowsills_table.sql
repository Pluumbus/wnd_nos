ON CONFLICT (width) DO UPDATE SET
  price = EXCLUDED.price;

-- Таблица для заглушек подоконников и прочих комплектующих
CREATE TABLE IF NOT EXISTS public.windowsill_accessories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  code text NOT NULL UNIQUE,
  name text NOT NULL,
  price numeric NOT NULL DEFAULT 0
);

-- Вставляем заглушки
INSERT INTO public.windowsill_accessories (code, name, price) VALUES
  ('CAP', 'Заглушка подоконника', 600)
ON CONFLICT (code) DO UPDATE SET
  name = EXCLUDED.name,
  price = EXCLUDED.price;

-- Комментарии
COMMENT ON TABLE public.windowsills IS 'Справочник подоконников по ширине с ценами за п.м.';
COMMENT ON TABLE public.windowsill_accessories IS 'Комплектующие к подоконникам (заглушки и т.д.)';
