-- Таблица для подоконников
-- Цены за погонный метр

CREATE TABLE IF NOT EXISTS public.windowsills (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  width integer NOT NULL UNIQUE, -- Ширина в мм
  price numeric NOT NULL DEFAULT 0 -- Цена за п.м.
);

-- Вставляем данные подоконников
INSERT INTO public.windowsills (width, price) VALUES
